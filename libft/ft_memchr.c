#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	unsigned char		c2;
	size_t				i;
	const unsigned char	*s2;

	s2 = (const unsigned char *)s;
	c2 = (unsigned char)c;
	i = 0;
	while (i < n)
	{
		if (s2[i] == c2)
			return ((void *)&s2[i]);
		i++;
	}
	return (NULL);
}
